// Interface language (English / Burmese). The VIDEO languages (Thai / Myanmar) are separate: see LANGS in api.js.
// t("key", { n: 3 }) → text with {n} filled in; a missing Burmese text falls back to English.

export const UI_LANGS = { my: "မြန်မာ", en: "EN" };
const KEY = "uiLang";

let current = (() => {
  try { const v = localStorage.getItem(KEY); if (v && UI_LANGS[v]) return v; } catch { /* private window */ }
  return typeof navigator !== "undefined" && /^my\b/i.test(navigator.language || "") ? "my" : "en";
})();

export const getLang = () => current;
export function setLang(l) {
  if (!UI_LANGS[l]) return;
  current = l;
  try { localStorage.setItem(KEY, l); } catch { /* private window */ }
}

export function t(key, vars) {
  const s = DICT[current]?.[key] ?? DICT.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m)) : s;
}

